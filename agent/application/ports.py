from typing import Protocol, ContextManager, Any
class LanguageModel(Protocol):
    def __call__(self, messages: list, schema: dict | None = None) -> str: ...
class KnowledgeBase(Protocol):
    def search(self, scope: str, query: str) -> Any: ...
class MessageSender(Protocol):
    def __call__(self, recipient: str, text: str) -> Any: ...
class UnitOfWork(Protocol):
    def transaction(self) -> ContextManager: ...
    def connection(self) -> ContextManager: ...

class CalendarProvider(Protocol):
    def list_events(self,start:str,end:str) -> list: ...
    def conflicts(self,start:str,end:str,exclude:int|None=None) -> list: ...
    def get(self,i:int): ...
    def create_event(self,title,start,end,category,priority,request_id=None) -> int: ...
    def update_event(self,i,start,end): ...
    def cancel_event(self,i): ...
